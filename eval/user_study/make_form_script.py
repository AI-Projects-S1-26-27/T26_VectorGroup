"""Write a Google Apps Script that builds the two rating forms for you.   OWNER: Mani

Making 2 forms x 30 items x 3 questions by hand takes an hour. Instead:

  1. python -m eval.user_study.build_study            (creates results/user_study/items.csv)
  2. python -m eval.user_study.make_form_script       (creates results/user_study/make_forms.gs)
  3. Go to https://script.google.com -> New project -> delete the sample code -> paste the
     whole make_forms.gs -> click Run (allow the permissions it asks for).
  4. Open View -> Logs / Execution log: it prints the two form links (sheet A and sheet B).
     Give raters sheet A and sheet B alternately (1st person A, 2nd person B, ...).
  5. When responses are in: in each form open Responses -> "Link to Sheets" -> File ->
     Download -> CSV, then run eval/user_study/convert_form.py (see its docstring).

The forms use one page per item: the board (emoji), the program's move and reason, then
three 1-5 scale questions titled "Item N: Correctness / Clarity / Usefulness".
"""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

from eval.user_study.build_study import condition

TEMPLATE = r"""// Generated by eval/user_study/make_form_script.py -- paste into script.google.com and Run.
const ITEMS = __ITEMS__;
const INTRO = __INTRO__;

function makeForms() {
  ['A', 'B'].forEach(function (sheet) {
    const form = FormApp.create('Connect-4 explanation ratings (sheet ' + sheet + ')');
    form.setDescription(INTRO);
    form.setProgressBar(true);
    ITEMS.forEach(function (it) {
      const text = (sheet === 'A') === (it.item % 2 === 1) ? it.agent_text : it.baseline_text;
      form.addPageBreakItem()
          .setTitle('Item ' + it.item + ' of ' + ITEMS.length)
          .setHelpText('Player to move: ' + it.player_to_move + ' (red moves first; columns 1-7 from the left)\n\n' +
                       it.board + '\n\nProgram\'s move and reason:\n' + text);
      ['Correctness', 'Clarity', 'Usefulness'].forEach(function (dim) {
        form.addScaleItem()
            .setTitle('Item ' + it.item + ': ' + dim)
            .setBounds(1, 5)
            .setLabels('very bad', 'very good')
            .setRequired(true);
      });
    });
    Logger.log('Sheet ' + sheet + ' -> fill in: ' + form.getPublishedUrl() + '  (edit: ' + form.getEditUrl() + ')');
  });
}
"""

INTRO = ("A Connect-4 program chose a column and gave a reason. For each board, rate the reason "
         "from 1 (very bad) to 5 (very good): Correctness = is what it says true on this board? "
         "Clarity = is it easy to understand? Usefulness = does it help you understand the move? "
         "30 items, about 10 minutes. No personal details are collected.")


def build_script(items_csv: Path) -> str:
    with open(items_csv, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    items = [dict(item=int(r["item"]), player_to_move=r["player_to_move"], board=r["board"],
                  agent_text=r["agent_text"], baseline_text=r["baseline_text"]) for r in rows]
    # self-check: the JS rule (odd items show the agent on sheet A) must match build_study
    for it in items:
        assert (condition(it["item"], "A") == "agent") == (it["item"] % 2 == 1)
    return (TEMPLATE.replace("__ITEMS__", json.dumps(items, ensure_ascii=False, indent=1))
            .replace("__INTRO__", json.dumps(INTRO, ensure_ascii=False)))


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--items", default="results/user_study/items.csv")
    p.add_argument("--out", default="results/user_study/make_forms.gs")
    a = p.parse_args(argv)
    Path(a.out).write_text(build_script(Path(a.items)), encoding="utf-8")
    print(f"wrote {a.out}: paste it into https://script.google.com and press Run")


if __name__ == "__main__":
    main()
